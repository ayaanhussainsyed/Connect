#!/usr/bin/env python3
"""Generate docs/MESSAGES.md: the final customer messages, exactly as the system produces them.

    .venv/bin/python scripts/gen_messages.py

Runs offline (LLM_ENABLED=0), so the output is deterministic and contains only template text built from data.
"""
from __future__ import annotations

import os
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["LLM_ENABLED"] = "0"

from cs.compose import (compose_autopilot_note, compose_confirmation,  # noqa: E402
                        compose_emergency, compose_followup)
from cs.confirm import where_it_shows  # noqa: E402

PY = str(ROOT / ".venv" / "bin" / "python")
ENV = {**os.environ, "LLM_ENABLED": "0"}


def cli(*args: str) -> str:
    out = subprocess.run([PY, *args], cwd=ROOT, env=ENV, capture_output=True, text=True, timeout=300)
    return (out.stdout or out.stderr).rstrip()


def block(title: str, text: str) -> str:
    return f"### {title}\n```\n{text}\n```\n"


def msg(m: dict) -> str:
    buttons = "  ".join(f"[{b['title']}]" for b in m.get("buttons", []))
    return m["text"] + (f"\n  {buttons}" if buttons else "")


def main() -> None:
    parts = ["# Final customer messages (as text)\n",
             "Generated by `scripts/gen_messages.py` from the real composer (`cs/compose.py`, `cs/profile/`), "
             "offline (no LLM), so every fact is template text filled from data. Dates and hours come from the "
             "engine's suggestions for the 2026 season.\n"]

    parts.append("## 1. Season cards (first contact, WhatsApp, one per language)\n")
    for eid, lang in [("FI-D0001", "fi"), ("SE-D0008", "sv"), ("NO-D0009", "nb"), ("FI-D0001", "en")]:
        parts.append(block(f"{eid} · {lang}", cli("-m", "cs.compose", eid, "--lang", lang, "--channel", "WHATSAPP")))
    parts.append(block("FI-D0001 · fi · SMS (digits instead of buttons)",
                       cli("-m", "cs.compose", "FI-D0001", "--lang", "fi", "--channel", "SMS")))

    biz = {"name": "Kahvila Aurora"}
    wis = where_it_shows("FI-D0001")
    changes = {"2026-12-24": "07:30-13:00", "2026-12-25": "closed", "2027-01-01": "closed"}

    parts.append("## 2. Follow-ups after the owner decides\n")
    for lang in ("fi", "en"):
        parts.append(block(f"Approve · {lang}", msg(compose_followup("APPROVE", lang, business=biz))))
        parts.append(block(f"Approve + every year · {lang}", msg(compose_followup("APPROVE_EVERY_YEAR", lang, business=biz))))
        parts.append(block(f"Edit read-back (\"we close at 14 on the 24th\") · {lang}",
                           msg(compose_followup("EDIT", lang, business=biz, values={"2026-12-24": "07:30-14:00"}))))
        parts.append(block(f"No thanks · {lang}", msg(compose_followup("DECLINE", lang, business=biz))))
        parts.append(block(f"Reminder (no reply yet) · {lang}",
                           msg(compose_followup("REMINDER", lang, business=biz, deadline=date(2026, 12, 17),
                                                today=date(2026, 12, 14)))))
        parts.append(block(f"Confirmation: where it shows · {lang}",
                           msg(compose_confirmation(biz, changes, wis, lang))))

    parts.append("## 3. \"Closed today\" (owner-initiated emergency; the reason is never stored)\n")
    for lang in ("fi", "en"):
        parts.append(block(f"Closed today · {lang}",
                           msg(compose_emergency(biz, date(2026, 12, 12), lang, today=date(2026, 12, 12),
                                                 where_it_shows=wis))))

    parts.append("## 4. Season Autopilot note (next season, standing permission)\n")
    for lang in ("fi", "en"):
        parts.append(block(f"Autopilot · {lang}",
                           msg(compose_autopilot_note({"name": "Tilitoimisto Otso"},
                                                      {"2026-12-24": "closed", "2026-12-25": "closed",
                                                       "2027-01-01": "closed"}, lang))))

    parts.append("## 5. Whole profile: weekly hours that changed, and a reply to a closed-door review\n")
    parts.append(block("SE-D0016 Restaurang Fyren · sv", cli("-m", "cs.profile", "drift", "SE-D0016", "--lang", "sv")))
    parts.append(block("FI-D0012 Tilitoimisto Otso · fi",
                       cli("-m", "cs.profile", "reviews", "FI-D0012", "--lang", "fi", "--no-db")))

    out = ROOT / "docs" / "MESSAGES.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
